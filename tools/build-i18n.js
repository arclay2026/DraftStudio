// Builds js/i18n/<code>.js from i18n/<code>.json. Don't edit the built files by hand.
//
// Each JSON file has:
//   "strings":  { "English text": "translation", ... }
//   "patterns": { "^(\\d+) icons?$": "$1 icônes", ... }  English regex -> output;
//               $1, $2... insert the captured parts (translated when they are in "strings")
//
// Run: node tools/build-i18n.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const src = path.join(root, "i18n");
const out = path.join(root, "js", "i18n");
fs.mkdirSync(out, { recursive: true });

for (const file of fs.readdirSync(src).filter(f => f.endsWith(".json")).sort()) {
  const code = path.basename(file, ".json");
  const data = JSON.parse(fs.readFileSync(path.join(src, file), "utf8"));
  const strings = data.strings || {};
  const patterns = Object.entries(data.patterns || {});
  patterns.forEach(([re]) => new RegExp(re)); // fail early on a broken pattern
  const body = `/* Generated by tools/build-i18n.js from i18n/${file}. Don't edit by hand. */\n` +
    `window.DS_I18N = ${JSON.stringify({ lang: code, strings, patterns })};\n`;
  fs.writeFileSync(path.join(out, code + ".js"), body);
  console.log(`${code}: ${Object.keys(strings).length} strings, ${patterns.length} patterns`);
}
