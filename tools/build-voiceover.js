// Writes the narration scripts for the Design Basics lessons to voiceover/, one file
// per lesson, split into parts that each fit one ElevenLabs generation. The text comes
// from js/academy-lessons.js, worded for speaking. Each part is saved as
// audio/<lesson>-<part>.mp3; the Learn page plays those files when they exist.
// Run: node tools/build-voiceover.js (tools/bump.sh runs it too)
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.join(__dirname, "..");
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "js", "academy-lessons.js"), "utf8"), sandbox);
const { DS_LESSONS: LESSONS, DS_LESSON_SCRIPT: script } = sandbox.window;
const out = path.join(root, "voiceover");
fs.mkdirSync(out, { recursive: true });

const rule = "─".repeat(60);
const index = [];
LESSONS.forEach((l, i) => {
  const s = script(l, i);
  const name = `${String(i + 1).padStart(2, "0")}-${l.key}.txt`;
  let txt = `DESIGN BASICS · LESSON ${i + 1} · ${l.title.toUpperCase()}\n` +
    `Narration script for ElevenLabs. ${s.parts.length} part${s.parts.length > 1 ? "s" : ""}.\n` +
    `Paste only the text between the lines into ElevenLabs, one part at a time.\n`;
  s.parts.forEach((p, k) => {
    const body = p.map(j => s.blocks[j]).join("\n\n");
    const file = path.basename(s.file(k));
    txt += `\n${rule}\nPART ${k + 1} OF ${s.parts.length}  ·  save as: ${file}  ·  ${body.length.toLocaleString("en")} characters\n${rule}\n\n${body}\n`;
    index.push(`| ${i + 1} | ${l.title} | ${k + 1} | \`audio/${file}\` | ${body.length.toLocaleString("en")} |`);
  });
  fs.writeFileSync(path.join(out, name), txt);
});

fs.writeFileSync(path.join(out, "README.md"), `# Lesson narration (ElevenLabs)

The Learn page reads each lesson aloud. When a lesson's recordings are in \`audio/\`,
visitors hear them; until then their browser's own voice reads the same script.
These files are generated by \`node tools/build-voiceover.js\`. Don't edit them by hand:
change the lesson text in \`js/academy-lessons.js\` instead.

## Making the recordings

1. Open a lesson script here (for example \`01-colour.txt\`).
2. In ElevenLabs, open **Text to Speech** and pick one voice for every lesson, so the
   course sounds like one narrator. Suggested settings: model **Eleven Multilingual v2**,
   Stability about 50%, Similarity about 75%, Style 0 to 15%, Speaker boost on.
3. Paste the text (not the PART lines) and generate. If ElevenLabs won't take it all at
   once, record it in as many pieces as you need, in order. Listen once; regenerate if a
   word sounds wrong.
4. Download the pieces as **MP3** and upload them anywhere in the repository.
5. Join and time them with one command (ffmpeg and node needed), for example:

   \`python3 tools/align-audio.py colour "Color lesson.mp3" "Color lesson continuation.mp3"\`

   This writes \`audio/colour.mp3\` (the whole lesson) and \`audio/colour.json\` (the second
   each paragraph starts, found from the narrator's pauses), so the highlight follows the
   voice exactly. The original pieces can then be deleted.

Alternatively, save each part exactly as the script names it (for example \`colour-1.mp3\`)
in \`audio/\`: the site plays those in order too, with the highlight timed by length.

## When a lesson changes

If you edit a lesson's text, run \`bash tools/bump.sh\` (or \`node tools/build-voiceover.js\`),
then record the changed parts again. A recording that no longer matches the text
still plays, but the highlight drifts.

## Files

| Lesson | Title | Part | Save as | Characters |
|---|---|---|---|---|
${index.join("\n")}
`);
fs.mkdirSync(path.join(root, "audio"), { recursive: true });
if (!fs.existsSync(path.join(root, "audio", ".gitkeep"))) fs.writeFileSync(path.join(root, "audio", ".gitkeep"), "");
console.log(`voiceover/: ${LESSONS.length} scripts, ${index.length} parts`);
