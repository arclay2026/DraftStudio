// Bundles every SVG in files/icons/ into js/icons.js so the site can draw
// them inline (recolourable, no extra downloads).
// Run after adding or changing an icon:   node tools/build-icons.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const dir = path.join(root, "files/icons");
const out = {};
for (const file of fs.readdirSync(dir).filter(f => f.endsWith(".svg")).sort()) {
  const svg = fs.readFileSync(path.join(dir, file), "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
  out[file.replace(/\.svg$/, "")] = inner;
}
const body = "/* Generated by tools/build-icons.js from files/icons/. Don't edit by hand. */\n" +
  "window.DS_ICONS = " + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ";\n";
fs.writeFileSync(path.join(root, "js/icons.js"), body);
console.log("Wrote js/icons.js with " + Object.keys(out).length + " icons");
