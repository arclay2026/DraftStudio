#!/usr/bin/env python3
"""Lighter copies of the preview images, so pages load faster.

For every JPG/PNG in previews/ this writes two WebP copies:
  previews/sm/<name>.webp   640 px wide, for cards, search and chat thumbnails
  previews/md/<name>.webp  1400 px wide at most, for the big previews
Also writes js/preview-sizes.js (each preview's width and height).
The site uses them through imgSrc()/imgSet() in js/site.js and falls back to the original
file when a copy is missing, so a new design shows up even before this runs.
tools/bump.sh runs it (it needs Python 3 with Pillow: pip install pillow).
"""
import os
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("build-images: Pillow isn't installed (pip install pillow), skipped")

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "previews")
SIZES = {"sm": (640, 72), "md": (1400, 80)}  # folder: (max width, WebP quality)

made = 0
for name in sorted(os.listdir(SRC)):
    base, ext = os.path.splitext(name)
    if ext.lower() not in (".jpg", ".jpeg", ".png"):
        continue
    src = os.path.join(SRC, name)
    for folder, (width, quality) in SIZES.items():
        out = os.path.join(SRC, folder, base + ".webp")
        if os.path.exists(out) and os.path.getmtime(out) >= os.path.getmtime(src):
            continue
        os.makedirs(os.path.dirname(out), exist_ok=True)
        im = Image.open(src)
        im = im.convert("RGBA" if im.mode in ("RGBA", "LA", "P") else "RGB")
        if im.width > width:
            im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
        im.save(out, "WEBP", quality=quality, method=6)
        made += 1
# Every preview's size, so pages can reserve the space before pictures arrive
import json
sizes = {}
for name in sorted(os.listdir(SRC)):
    if os.path.splitext(name)[1].lower() in (".jpg", ".jpeg", ".png", ".webp"):
        with Image.open(os.path.join(SRC, name)) as im:
            sizes["previews/" + name] = list(im.size)
with open(os.path.join(ROOT, "js", "preview-sizes.js"), "w") as f:
    f.write("/* Generated by tools/build-images.py. Don't edit by hand. */\nwindow.DS_SIZES = " + json.dumps(sizes) + ";\n")
print(f"build-images: {made} WebP copies written")
