// Turns the two logo SVGs into logos.js (inner markup as strings) so card.html can inline them.
// Classes become plain fills; the watermark loses its fills so it takes the colour of its group.
const fs = require("fs"), path = require("path");
const inner = f => fs.readFileSync(path.join(__dirname, f), "utf8").replace(/[\s\S]*?<\/defs>/, "").replace(/<\/svg>\s*$/, "").trim();
const FILL = { "cls-1": "#ffff01", "cls-2": "#fe0002", "cls-3": "#fff200", "cls-4": "#fff" };
const main = inner("logo-main.svg").replace(/class="(cls-\d)"/g, (_, c) => `fill="${FILL[c]}"`);
const wm = inner("logo-watermark.svg").replace(/ class="cls-\d"/g, "");
fs.writeFileSync(path.join(__dirname, "logos.js"), `// generated by build-logos.js\nwindow.LOGO_MAIN = ${JSON.stringify(main)};\nwindow.LOGO_WM = ${JSON.stringify(wm)};\n`);
